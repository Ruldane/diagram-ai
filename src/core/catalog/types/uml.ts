/* ----------------------------------------------------------------- timing */

const TIMING = { left: 130, unit: 70, rowH: 44 };
const timingX = (time: number): number => TIMING.left + time * TIMING.unit;

/**
 * One value lifeline of a timing diagram: its name on the left, then one
 * elongated hexagon per state, touching tip to tip where the value changes.
 */
function valueLifeline(id: string, name: string, y: number, color: string, states: { text: string; from: number; to: number }[]): NodeSpec[] {
  return [
    label(`${id}-name`, name, { x: 0, y, w: TIMING.left - 20, h: TIMING.rowH }, { bold: true, align: "left", fontSize: 13 }),
    ...states.map((state, index) => ({
      id: `${id}-${index + 1}`,
      shape: "basic/hexagon",
      text: state.text,
      x: timingX(state.from),
      y,
      w: timingX(state.to) - timingX(state.from),
      h: TIMING.rowH,
      color,
      style: { fontSize: 12 },
    })),
  ];
}

/* ---------------------------------------------------- composite structure */

/** A port: a small square sitting on the inside of the classifier's border, with its name next to it. */
function port(id: string, name: string, x: number, y: number, side: "left" | "right"): NodeSpec[] {
  return [
    { id, shape: "basic/rect", text: "", parent: "service", x, y, w: 16, h: 16, color: "blue" },
    label(`${id}-name`, name, { x: side === "left" ? x - 136 : x + 22, y: y - 6, w: 130, h: 28 }, { ...MUTED_TEXT, align: side === "left" ? "right" : "left" }),
  ];
}

