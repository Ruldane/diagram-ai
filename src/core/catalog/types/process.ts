/* ------------------------------------------------------- customer journey */

const JOURNEY = { rowHeader: 120, columnW: 180, gap: 8, top: 60 };
const journeyX = (column: number): number => JOURNEY.rowHeader + column * (JOURNEY.columnW + JOURNEY.gap);

/** One row of a journey map: a caption on the left, then one cell per stage. */
function journeyRow(id: string, title: string, y: number, h: number, cells: string[]): NodeSpec[] {
  return [
    label(`${id}-title`, title, { x: 0, y, w: JOURNEY.rowHeader - 10, h }, { ...MUTED_TEXT, align: "left", bold: true }),
    ...cells.map((text, column) => ({
      id: `${id}-${column + 1}`,
      shape: "basic/rounded",
      text,
      x: journeyX(column),
      y,
      w: JOURNEY.columnW,
      h,
      style: { ...HAIRLINE, fontSize: 12, radius: 6 },
    })),
  ];
}

/* ------------------------------------------------------ service blueprint */

const BLUEPRINT = { laneW: 900, stripW: 40, columnW: 170, firstX: 80, stepW: 150, stepH: 50 };
const blueprintX = (column: number): number => BLUEPRINT.firstX + column * (BLUEPRINT.columnW + 30);

function blueprintLane(id: string, title: string, y: number, h: number, color?: string): NodeSpec {
  return {
    id,
    shape: "uml/swimlane",
    text: title,
    x: 0,
    y,
    w: BLUEPRINT.laneW,
    h,
    data: { orientation: "horizontal" },
    ...(color ? { color } : {}),
  };
}

function blueprintStep(id: string, text: string, lane: string, column: number, laneY: number, laneH: number, color?: string): NodeSpec {
  return {
    id,
    shape: "basic/rounded",
    text,
    parent: lane,
    x: blueprintX(column),
    y: laneY + (laneH - BLUEPRINT.stepH) / 2,
    w: BLUEPRINT.stepW,
    h: BLUEPRINT.stepH,
    style: { fontSize: 12 },
    ...(color ? { color } : {}),
  };
}

